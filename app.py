def extract_top_n(query):
    q = normalize_text(query)

    m = re.search(r"(?:top|前)(\d+)", q)
    if m:
        return max(1, min(int(m.group(1)), 20))

    zh_map = {
        "一":1, "二":2, "三":3, "四":4, "五":5,
        "六":6, "七":7, "八":8, "九":9, "十":10, "兩":2
    }
    m = re.search(r"前([一二三四五六七八九十兩])", q)
    if m:
        return zh_map[m.group(1)]

    if any(k in q for k in ["王", "第一", "最多", "最高", "最好", "最強", "最少", "最低"]):
        return 1

    return None

