def answer_ranking(metric, top_n, year=DEFAULT_YEAR):
    df = rank_dataframe(metric, year=year)
    col = metric["col"]
    label = metric["label"]

    if df.empty or col not in df.columns:
        return f"我目前可分析的年份有：{', '.join(map(str, AVAILABLE_YEARS))}。"

    ranked = df.dropna(subset=[col]).sort_values(
        col,
        ascending=not metric["descending"]
    ).head(top_n)

    if ranked.empty:
        return f"我目前可分析的年份有：{', '.join(map(str, AVAILABLE_YEARS))}。"

    integer_cols = {"home_run", "b_rbi", "r_total_stolen_base", "r_run", "p_win", "p_loss"}

    if top_n == 1:
        row = ranked.iloc[0]
        value = fmt_num(row[col], 0 if col in integer_cols else 3)
        return f"{year} {label} 第一名是 {row['last_name, first_name']}，{label} = {value}。"

    lines = []
    for i, (_, row) in enumerate(ranked.iterrows(), start=1):
        value = fmt_num(row[col], 0 if col in integer_cols else 3)
        lines.append(f"{i}. {row['last_name, first_name']} — {label} {value}")

    return "\n".join(lines)

