def build_name_variants(df):
    names = df["last_name, first_name"].fillna("").astype(str).unique()

    first_counter = Counter()
    last_counter = Counter()

    for name in names:
        parts = [p.strip() for p in name.split(",")]
        if len(parts) == 2:
            last_name = normalize_text(parts[0])
            first_name = normalize_text(parts[1])
            if first_name:
                first_counter[first_name] += 1
            if last_name:
                last_counter[last_name] += 1

    name_map = {}

    for name in names:
        parts = [p.strip() for p in name.split(",")]
        variants = {normalize_text(name)}

        if len(parts) == 2:
            last_name = normalize_text(parts[0])
            first_name = normalize_text(parts[1])

            variants |= {
                f"{first_name}{last_name}",
                f"{last_name}{first_name}",
                f"{first_name} {last_name}",
                f"{last_name} {first_name}",
            }

            # 只有在名字本身夠長且不重複時，才加入單獨 first / last name
            if first_name and len(first_name) >= 4 and first_counter[first_name] == 1:
                variants.add(first_name)
            if last_name and len(last_name) >= 4 and last_counter[last_name] == 1:
                variants.add(last_name)

        name_map[name] = sorted(
            [v for v in variants if v],
            key=len,
            reverse=True
        )

    return name_map

