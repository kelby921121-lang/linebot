def player_aliases(name):
    if pd.isna(name):
        return []

    name = str(name).strip()
    aliases = {name}

    if "," in name:
        last, first = [x.strip() for x in name.split(",", 1)]
        aliases.add(f"{first} {last}")
        aliases.add(f"{first}{last}")
        aliases.add(f"{last}{first}")

    return [normalize_text(x) for x in aliases if x]

