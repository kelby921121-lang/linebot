# 基礎工具
def safe_float(x):
    try:
        if pd.isna(x):
            return np.nan
        return float(x)
    except Exception:
        return np.nan


def fmt_num(x, digits=3):
    x = safe_float(x)
    if np.isnan(x):
        return "N/A"

    if digits <= 0:
        return str(int(round(x)))

    return f"{x:.{digits}f}".rstrip("0").rstrip(".")


def normalize_text(text):
    if pd.isna(text):
        return ""
    text = str(text).lower()
    text = re.sub(r"[^a-z0-9一-鿿]", "", text)
    return text


def zscore(series, higher_better=True):
    s = pd.to_numeric(series, errors="coerce")
    mean = s.mean()
    std = s.std()

    if std == 0 or pd.isna(std):
        z = pd.Series([0] * len(s), index=s.index)
    else:
        z = (s - mean) / std

    return z if higher_better else -z


