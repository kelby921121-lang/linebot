def build_metric_catalog():
    catalog = []

    for item in STAT_CANDIDATES:
        df = hitters if item["role"] == "hitter" else pitchers
        if item["col"] not in df.columns:
            continue

        new_item = dict(item)

        aliases = set()
        for x in item["aliases"]:
            nx = normalize_text(x)
            if len(nx) >= 2:
                aliases.add(nx)

        label_alias = normalize_text(item["label"])
        if len(label_alias) >= 2:
            aliases.add(label_alias)

        col_alias = normalize_text(item["col"])
        if len(col_alias) >= 2:
            aliases.add(col_alias)

        new_item["aliases"] = sorted(aliases, key=len, reverse=True)
        catalog.append(new_item)

    return catalog

